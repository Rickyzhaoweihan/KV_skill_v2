"""[D19] Materialize Shakespeare's plays (Project Gutenberg #100, public domain) into the xenc doc-QA schema,
in two paired variants built from the SAME questions:

  shakespeare_split     the original play text            (prior and document AGREE)
  shakespeare_cf_split  the play with its major named characters consistently PERMUTED (a derangement:
                        speaker prefixes, dramatis personae and every in-text mention), so the document
                        CONTRADICTS the reader's memorized play                (prior and document CONFLICT)

One document = one play (37 plays; ~20k-45k Qwen tokens). Questions are generated by rule from the speaker markup,
so they are exactly gradable:
  * speaker  (4-way MCQ): "Which character speaks the line: '<quote>'?"  The quote is the opening of a speech
    (stage directions removed) that occurs exactly once in the play. All four options are permuted ("named")
    characters, and the option set ALWAYS contains both the original speaker X and its counterfactual image
    sigma(X), so original and CF items share the option set and differ only in the gold label.
    In the CF split `meta.prior_label` is the label of X (what a reader that ignores the document says).
  * act      (5-way MCQ, Acts I-V): "In which act does this line occur?"  Unchanged by renaming: a no-conflict
    control in the CF split (`meta.conflict` = False).
Plays are split by play (seed 42): train 24 / val 5 / test 8, identically for both variants.

  python -I scripts/data/prepare_shakespeare.py [--raw data/raw/shakespeare/pg100.txt] [--out_dir data]
"""
from __future__ import annotations

import argparse
import random
import re
import sys
from collections import Counter, OrderedDict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from xenc.doc_tasks import load_qwen_tokenizer, print_summary, write_split  # noqa: E402

NAME, CF = "shakespeare", "shakespeare_cf"
NON_PLAYS = {"THE SONNETS", "A LOVER’S COMPLAINT", "THE PASSIONATE PILGRIM", "THE PHOENIX AND THE TURTLE",
             "THE RAPE OF LUCRECE", "VENUS AND ADONIS"}
# speaker labels that are roles/titles, not names: never permuted, never used as options
GENERIC = set("""KING QUEEN PRINCE PRINCESS DUKE DUCHESS CLOWN FOOL NURSE GHOST CHORUS PROLOGUE EPILOGUE MESSENGER
SERVANT PORTER DOCTOR GENTLEMAN GENTLEWOMAN LORD LADY CAPTAIN SOLDIER OFFICER ALL BOTH PAGE BOY WATCHMAN SHERIFF
CITIZEN HOST HOSTESS SAILOR PRIEST FRIAR BISHOP CARDINAL KEEPER GAOLER JAILER POET PAINTER PLAYER MAYOR HERALD WIFE
WIDOW ATTENDANT MURDERER WITCH SENATOR TRIBUNE LIEUTENANT MASTER BOATSWAIN SHEPHERD SECRETARY SCRIVENER CONSTABLE
MARINER PURSUIVANT ARCHBISHOP ABBESS ABBOT DAUGHTER SON MOTHER FATHER EMPEROR EMPRESS GOVERNOR GENERAL COUNTESS
COUNT MARQUESS EARL BAWD PANDAR APOTHECARY MUSICIAN SERVINGMAN GROOM TAPSTER VINTNER DRAWER CARRIER CHAMBERLAIN
CLERK USHER SHIPMASTER TUTOR ANOTHER FORESTER LORDS LADIES SERVANTS SOLDIERS CITIZENS OUTLAW PIRATE BEADLE
SURVEYOR SCOUT SENTINEL GARDENER GUARD JUSTICE ESQUIRE MAID OLD YOUNG MERCHANT BASTARD PROVOST WOOER
SCHOOLMASTER DAUPHIN""".split())
# names that are also common English words (a Title-case rename would hit sentence-initial ordinary words)
GENERIC |= {"SPEED", "SIMPLE", "BOTTOM", "MOTH", "ELBOW", "LANCE"}
LETTERS = "ABCDE"
ROMAN = ["I", "II", "III", "IV", "V"]
SPEAKER_RE = re.compile(r"^([A-Z][A-Z’' ,&-]*[A-Z])\.\s*$")
ACT_RE = re.compile(r"^ACT ([IVX]+)\b")
DIRECTION_RE = re.compile(r"\[[^\]]*\]")


def _norm(s: str) -> str:
    return " ".join(re.sub(r"[^a-z0-9 ]", " ", s.lower().replace("’", "'")).split())


def split_works(raw: str) -> "OrderedDict[str, str]":
    body = raw.split("*** START OF THE PROJECT GUTENBERG EBOOK 100 ***", 1)[-1]
    body = body.split("*** END OF THE PROJECT GUTENBERG EBOOK 100 ***", 1)[0]
    lines = body.splitlines()
    ci = next(i for i, ln in enumerate(lines) if ln.strip() == "Contents")
    titles, j = [], ci + 1
    while j < len(lines) and (not lines[j].strip() or lines[j].startswith("    ")):
        if lines[j].strip():
            titles.append(lines[j].strip())
        j += 1
    starts = []
    for t in titles:  # the work starts at its first column-0 title line after the table of contents
        k = next(i for i in range(j, len(lines)) if lines[i].rstrip() == t)
        starts.append((k, t))
    starts.sort()
    works = OrderedDict()
    for n, (k, t) in enumerate(starts):
        end = starts[n + 1][0] if n + 1 < len(starts) else len(lines)
        works[t] = "\n".join(lines[k:end]).strip() + "\n"
    return works


def parse_speeches(text: str) -> list[dict]:
    """[{speaker, act, text}] from the play's speaker markup (speech = lines after 'NAME.' up to a blank line)."""
    out, act, lines, i = [], None, text.splitlines(), 0
    while i < len(lines):
        ln = lines[i].rstrip()
        m = ACT_RE.match(ln)
        if m:
            act = m.group(1)
        m = SPEAKER_RE.match(ln)
        if m and act in ROMAN:
            body = []
            i += 1
            while i < len(lines) and lines[i].strip():
                body.append(lines[i].strip())
                i += 1
            speech = " ".join(DIRECTION_RE.sub(" ", " ".join(body)).split())
            if speech:
                out.append({"speaker": m.group(1), "act": act, "text": speech})
            continue
        i += 1
    return out


def named_speakers(speeches, min_speeches: int) -> list[str]:
    c = Counter(s["speaker"] for s in speeches)
    return [sp for sp, n in c.most_common() if n >= min_speeches and " " not in sp and sp not in GENERIC
            and sp.isalpha()]


def derangement(names: list[str], rng: random.Random) -> dict[str, str]:
    while True:
        perm = names[:]
        rng.shuffle(perm)
        if all(a != b for a, b in zip(names, perm)):
            return dict(zip(names, perm))


def rename(text: str, sigma: dict[str, str]) -> str:
    """Simultaneous whole-word replacement of every permuted name in UPPER and Title case."""
    table = {}
    for a, b in sigma.items():
        table[a] = b
        table[a.title()] = b.title()
    pat = re.compile(r"\b(" + "|".join(sorted(map(re.escape, table), key=len, reverse=True)) + r")\b")
    return pat.sub(lambda m: table[m.group(1)], text)


def make_items(slug, play, speeches, sigma, rng, n_speaker, n_act, quote_words):
    """Paired (original, cf) item lists for one play."""
    ntext = _norm(play)
    named = list(sigma)
    seen, cands = set(), []
    for k, s in enumerate(speeches):
        w = s["text"].split()
        if len(w) < 8:
            continue
        q = " ".join(w[:quote_words])
        nq = _norm(q)
        if len(nq.split()) < 6 or nq in seen or ntext.count(nq) != 1:
            continue
        seen.add(nq)
        cands.append((k, q))
    rng.shuffle(cands)
    sp_c = [(k, q) for k, q in cands if speeches[k]["speaker"] in sigma][:n_speaker]
    used = {k for k, _ in sp_c}
    act_c = [(k, q) for k, q in cands if k not in used][:n_act]
    orig, cf = [], []
    for k, q in sp_c:
        x = speeches[k]["speaker"]
        sx = sigma[x]
        others = [n for n in named if n not in (x, sx)]
        opts = [x, sx] + rng.sample(others, 2)
        rng.shuffle(opts)
        lab = {o: LETTERS[j] for j, o in enumerate(opts)}
        choices = [{"label": LETTERS[j], "text": o.title()} for j, o in enumerate(opts)]
        base = {"kind": "speaker", "play": slug, "act": speeches[k]["act"], "speech_index": k,
                "orig_speaker": x.title(), "cf_speaker": sx.title()}
        qo = f"In this play, which character speaks the line beginning: \"{q}\"?"
        qc = f"In this play, which character speaks the line beginning: \"{rename(q, sigma)}\"?"
        orig.append({"question": qo, "choices": choices, "answers": [x.title()], "correct_label": lab[x],
                     "meta": {**base, "conflict": False}})
        cf.append({"question": qc, "choices": choices, "answers": [sx.title()], "correct_label": lab[sx],
                   "meta": {**base, "conflict": True, "prior_label": lab[x]}})
    for k, q in act_c:
        a = speeches[k]["act"]
        choices = [{"label": LETTERS[j], "text": f"Act {r}"} for j, r in enumerate(ROMAN)]
        lab = LETTERS[ROMAN.index(a)]
        base = {"kind": "act", "play": slug, "act": a, "speech_index": k, "conflict": False}
        orig.append({"question": f"In which act of this play does the line beginning \"{q}\" occur?",
                     "choices": choices, "answers": [f"Act {a}"], "correct_label": lab, "meta": dict(base)})
        cf.append({"question": f"In which act of this play does the line beginning \"{rename(q, sigma)}\" occur?",
                   "choices": choices, "answers": [f"Act {a}"], "correct_label": lab,
                   "meta": {**base, "prior_label": lab}})
    return orig, cf


def _slug(title: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", title.lower().replace("’", "")).strip("_")[:48]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default=str(REPO / "data/raw/shakespeare/pg100.txt"))
    ap.add_argument("--out_dir", default=str(REPO / "data"))
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--n_speaker", type=int, default=40)
    ap.add_argument("--n_act", type=int, default=20)
    ap.add_argument("--min_speeches", type=int, default=12)
    ap.add_argument("--max_named", type=int, default=10)
    ap.add_argument("--quote_words", type=int, default=14)
    ap.add_argument("--n_val", type=int, default=5)
    ap.add_argument("--n_test", type=int, default=8)
    args = ap.parse_args()

    works = split_works(Path(args.raw).read_text(encoding="utf-8"))
    plays = OrderedDict((t, x) for t, x in works.items() if t not in NON_PLAYS)
    slugs = sorted(_slug(t) for t in plays)
    order = list(slugs)
    random.Random(args.seed).shuffle(order)
    test_s, val_s = set(order[:args.n_test]), set(order[args.n_test:args.n_test + args.n_val])
    split_of = {s: ("test" if s in test_s else "val" if s in val_s else "train") for s in slugs}

    docs_o, docs_c = {}, {}
    splits_o = {s: [] for s in ("train", "val", "test")}
    splits_c = {s: [] for s in ("train", "val", "test")}
    sigmas = {}
    for title, text in plays.items():
        slug = _slug(title)
        rng = random.Random(f"{args.seed}:{slug}")
        speeches = parse_speeches(text)
        named = named_speakers(speeches, args.min_speeches)[:args.max_named]
        assert len(named) >= 4, (title, named)
        sigma = derangement(named, rng)
        sigmas[slug] = sigma
        did_o, did_c = f"{NAME}_{slug}", f"{CF}_{slug}"
        docs_o[did_o] = {"text": text, "title": title.title()}
        docs_c[did_c] = {"text": rename(text, sigma), "title": rename(title, sigma).title()}
        orig, cf = make_items(slug, text, speeches, sigma, rng, args.n_speaker, args.n_act, args.quote_words)
        sp = split_of[slug]
        for name, did, items, dst in ((NAME, did_o, orig, splits_o), (CF, did_c, cf, splits_c)):
            for it in items:
                it["meta"]["sigma"] = {a.title(): b.title() for a, b in sigma.items()} if name == CF else None
                dst[sp].append({"key": f"{name}_{slug}_q{len(dst[sp]):04d}", "doc_id": did,
                                "question": it["question"], "choices": it["choices"], "answers": it["answers"],
                                "correct_label": it["correct_label"], "task": name, "hop": None,
                                "meta": {k: v for k, v in it["meta"].items() if v is not None}})
    for split in splits_o:  # keys: make them per-split sequential like prepare_quality
        for name, dst in ((NAME, splits_o), (CF, splits_c)):
            for n, it in enumerate(dst[split]):
                it["key"] = f"{name}_{split}_{n:05d}"
    tok = load_qwen_tokenizer()
    out = Path(args.out_dir)
    for name, splits, docs in ((NAME, splits_o, docs_o), (CF, splits_c, docs_c)):
        index = write_split(out, name, splits, docs, tok)
        kinds = {s: dict(Counter(it["meta"]["kind"] for it in v)) for s, v in splits.items()}
        print_summary(name, splits, index, {"kinds": kinds,
                                            "test plays": sorted(test_s), "val plays": sorted(val_s)})
    n_conf = sum(it["meta"]["conflict"] for v in splits_c.values() for it in v)
    print(f"  CF items with prior != gold (conflict): {n_conf}; example sigma (hamlet): "
          f"{sigmas.get('the_tragedy_of_hamlet_prince_of_denmark')}")


if __name__ == "__main__":
    main()
